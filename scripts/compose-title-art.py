"""Composite actual 3D tiles, their shadow pass, and the clean illustration.

The user explicitly requested deterministic 3D rendering and compositing.
No tile shapes or symbols are generated by AI in the production composite.
"""
from pathlib import Path
import json
from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'assets/title'
layout = json.loads((ART / 'title-tiles-layout.json').read_text())
size = tuple(layout['referenceSize'])
base = Image.open(ART / 'salon-base-no-tiles.png').convert('RGBA')
if base.size != size:
    raise ValueError(f'Clean plate dimensions {base.size} do not match {size}')
tiles = Image.open(ART / 'title-tiles-3d.png').convert('RGBA')
beauty = Image.open(ART / 'title-tiles-on-plane.png').convert('RGBA')
plane = Image.open(ART / 'title-tiles-plane.png').convert('RGBA')
expected = tuple(v * layout['oversampling'] for v in size)
if any(image.size != expected for image in [tiles, beauty, plane]):
    raise ValueError('Render layers must use the configured oversampling')

# The difference from the same receiver without tiles gives only cast shadows.
level = max(1, plane.convert('L').getextrema()[1])
shadow = ImageChops.subtract(plane.convert('L'), beauty.convert('L'))
shadow = shadow.point([min(170, round(value * 255 / level)) for value in range(256)])
shadow = ImageChops.multiply(shadow, plane.getchannel('A'))
shadow = ImageChops.multiply(shadow, ImageChops.invert(tiles.getchannel('A')))
shadow = shadow.resize(size, Image.Resampling.LANCZOS)
shadow_layer = Image.new('RGBA', size, (0, 0, 0, 0))
shadow_layer.putalpha(shadow)
output = Image.alpha_composite(base, shadow_layer)

# A subtle contact shadow on the clothing behind the held tile.
metrics = json.loads((ART / 'title-tiles-render.json').read_text())
held = metrics['tiles'][-1]['bounds']
contact = Image.new('RGBA', size)
ImageDraw.Draw(contact).rounded_rectangle(
    (held['x'] + 1, held['y'] + 1,
     held['x'] + held['width'] + 1, held['y'] + held['height'] + 1),
    radius=2, fill=(0, 0, 0, 36))
output = Image.alpha_composite(output, contact.filter(ImageFilter.GaussianBlur(1)))
output = Image.alpha_composite(output, tiles.resize(size, Image.Resampling.LANCZOS))

# Restore the existing fingertips in front of the small 3D held tile.
foreground = Image.new('RGBA', size)
spec = layout['fingerForeground']
for y in range(spec['bounds'][1], spec['bounds'][3]):
    if spec['topMaxY'] < y < spec['bottomMinY']:
        continue
    for x in range(spec['bounds'][0], spec['bounds'][2]):
        r, g, b, a = base.getpixel((x, y))
        if r > 160 and g > 90 and b > 80 and r > g * 1.08:
            foreground.putpixel((x, y), (r, g, b, a))
output = Image.alpha_composite(output, foreground)
output.convert('RGB').save(ART / 'salon-composite.png', optimize=True)
print(f'Composited {metrics["tileCount"]} dimensioned 3D tiles into salon-composite.png')
